export function normalizedAssistantText(text: string) {
  return text
    .toLocaleLowerCase("ru-RU")
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}:/._-]+/gu, " ")
    .trim();
}

export function findAssistantArticles(
  message: string,
  section: AssistantSection,
  history = "",
) {
  const query = normalizedAssistantText(message);
  const words = query
    .split(/\s+/)
    .filter(
      (w) =>
        w.length > 3 &&
        ![
          "расскажи",
          "пожалуйста",
          "покажи",
          "такое",
          "почему",
          "можно",
          "сделать",
          "работает",
          "есть",
          "какие",
          "какой",
        ].includes(w),
    );
  const scored = ASSISTANT_KNOWLEDGE.map((article) => {
    const score = article.terms.reduce(
      (sum, term) =>
        sum + (query.includes(term) ? (term.includes(" ") ? 8 : 4) : 0),
      0,
    );
    return {
      article,
      score:
        score +
        words.reduce(
          (sum, w) =>
            sum + (normalizedAssistantText(article.title).includes(w) ? 2 : 0),
          0,
        ),
    };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);
  if (scored.length) return scored.slice(0, 2).map((x) => x.article);
  if (
    /^(а |и |подробнее|объясни|не понял|не понимаю|что это)/.test(query) &&
    history
  )
    return findAssistantArticles(history, section);
  if (/(?:здесь|тут|этом экране|эта кнопка|этот раздел)/.test(query))
    return [
      ASSISTANT_KNOWLEDGE.find((a) => a.id === section) ??
        ASSISTANT_KNOWLEDGE.find((a) => a.section === section),
    ].filter((a): a is AssistantArticle => !!a);
  return [];
}
